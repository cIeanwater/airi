"""Native Gemma function parsing and isolated, argument-bound tool replay."""

import copy
import json
import re

from .common import digest


class Arguments:
    def __init__(self, text):
        if len(text) > 65536:
            raise ValueError("Tool arguments exceed the replay budget")
        self.text, self.index = text, 0

    def space(self):
        while self.index < len(self.text) and self.text[self.index].isspace():
            self.index += 1

    def value(self):
        self.space()
        if self.text.startswith('<|"|>', self.index):
            self.index += 5
            end = self.text.find('<|"|>', self.index)
            if end < 0:
                raise ValueError("Unclosed native tool string")
            value, self.index = self.text[self.index:end], end + 5
            return value
        if self.index >= len(self.text):
            raise ValueError("Missing tool argument")
        start = self.text[self.index]
        if start in "{[":
            self.index += 1
            result = {} if start == "{" else []
            closing = "}" if start == "{" else "]"
            self.space()
            while self.index < len(self.text) and self.text[self.index] != closing:
                if start == "{":
                    if self.text.startswith('<|"|>', self.index) or self.text[self.index:self.index + 1] == '"':
                        key = self.value()
                        if not isinstance(key, str):
                            raise ValueError("Argument keys must be strings")
                    else:
                        match = re.match(r"[A-Za-z_][A-Za-z0-9_-]*", self.text[self.index:])
                        if not match:
                            raise ValueError("Invalid native argument key")
                        key = match.group(0)
                        self.index += len(key)
                    self.space()
                    if self.text[self.index:self.index + 1] != ":" or key in result:
                        raise ValueError("Invalid or duplicate argument key")
                    self.index += 1
                    result[key] = self.value()
                else:
                    result.append(self.value())
                self.space()
                if self.text[self.index:self.index + 1] == closing:
                    break
                if self.text[self.index:self.index + 1] != ",":
                    raise ValueError("Invalid native argument separator")
                self.index += 1
                self.space()
            if self.text[self.index:self.index + 1] != closing:
                raise ValueError("Unclosed native argument container")
            self.index += 1
            return result
        try:
            value, length = json.JSONDecoder().raw_decode(self.text[self.index:])
        except ValueError:
            raise ValueError("Invalid native scalar") from None
        self.index += length
        digest(value)
        return value

    def parse(self):
        result = self.value()
        self.space()
        if self.index != len(self.text) or not isinstance(result, dict):
            raise ValueError("Tool arguments must form one object")
        return result


def parse_calls(text, prefix="call"):
    calls = []
    for match in re.finditer(r"<\|tool_call>call:([A-Za-z0-9_-]+)(.*?)<tool_call\|>", text, re.S):
        calls.append({"id": prefix + "-" + str(len(calls)), "type": "function",
                      "function": {"name": match.group(1), "arguments": Arguments(match.group(2)).parse()}})
    if text.count("<|tool_call>") != len(calls):
        raise ValueError("Incomplete or unsupported native tool call")
    return calls


class ReplaySession:
    """Fixtures are host records, never generated by the evaluated model."""

    def __init__(self, case):
        self.environment = copy.deepcopy(case.get("environment", {}))
        self.environment_sha256 = digest(self.environment)
        self.steps = self.environment.get("tool_replay", [])
        self.index, self.effects = 0, []
        if self.steps and case.get("environment_sha256") != self.environment_sha256:
            raise ValueError("Replay environment changed")

    def execute(self, call):
        if self.index >= len(self.steps):
            raise ValueError("Tool call has no recorded replay step")
        step = self.steps[self.index]
        function = call["function"]
        if step["name"] != function["name"] or step["arguments"] != function["arguments"]:
            raise ValueError("Tool call differs from the recorded name or arguments")
        if step.get("status") != "finished" or "result" not in step:
            raise ValueError("Replay step has no completed external result")
        self.index += 1
        for effect in step.get("effects", []):
            self.effects.append({**copy.deepcopy(effect), "call_id": call["id"], "arguments_sha256": digest(function["arguments"])})
        return step["result"]

    def receipts(self, case, prediction):
        from .evaluation import prediction_hash

        return [{**effect, "case_id": case["id"], "actor_version": prediction["actor_version"],
                 "prediction_sha256": prediction_hash(prediction), "source": "replay",
                 "environment_sha256": self.environment_sha256} for effect in self.effects]
